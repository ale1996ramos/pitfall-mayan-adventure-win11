#!/usr/bin/env python3
"""Generate a C header embedding files as byte arrays: embed.py out.h name=path ..."""
import sys

out = sys.argv[1]
with open(out, "w") as f:
    f.write("/* generated by tools/embed.py - do not edit */\n#pragma once\n")
    for spec in sys.argv[2:]:
        name, path = spec.split("=", 1)
        data = open(path, "rb").read()
        if name.endswith("_ini"):
            data += b"\0"
        f.write(f"static const unsigned char {name}[{len(data)}] = {{\n")
        for i in range(0, len(data), 16):
            f.write("  " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
